#!/usr/bin/env node
// Harness-agnostic work board for Cinemacore.
// State lives in tasks/registry.json. TODO.md and BOARD.md are generated views.
// Any agent, in any harness, uses this so work is registered and tracked.
import { readFileSync, writeFileSync, appendFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const TASKS = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const REG = join(TASKS, 'registry.json');
const PROGRESS = join(TASKS, 'progress');
const STATUS = ['todo', 'doing', 'review', 'blocked', 'done'];
const ORDER = { doing: 0, review: 1, todo: 2, blocked: 3, done: 4 };

const now = () => new Date().toISOString();
const load = () => JSON.parse(readFileSync(REG, 'utf8'));
const save = (r) => writeFileSync(REG, JSON.stringify(r, null, 2) + '\n');

function parse(argv) {
  const out = { _: [] };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '-m') out.m = argv[++i];
    else if (a.startsWith('--')) out[a.slice(2)] = argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[++i] : true;
    else out._.push(a);
  }
  return out;
}
const req = (o, k, ctx) => (o[k] ? o[k] : (console.error(`missing --${k} (${ctx})`), process.exit(1)));
const find = (r, id) => r.tasks.find((t) => t.id === id) || (console.error(`no task ${id}`), process.exit(1));

function log(agent, line) {
  if (!agent) return;
  mkdirSync(PROGRESS, { recursive: true });
  const f = join(PROGRESS, `${agent}.md`);
  if (!existsSync(f)) writeFileSync(f, `# ${agent}\n\n`);
  appendFileSync(f, `- ${now()} — ${line}\n`);
}

function register(o) {
  const r = load();
  const id = req(o, 'agent', 'register');
  const harness = req(o, 'harness', 'register');
  const prev = r.agents.find((a) => a.id === id);
  const rec = { id, harness, model: o.model || prev?.model || null, startedAt: prev?.startedAt || now(), lastSeen: now() };
  if (prev) Object.assign(prev, rec); else r.agents.push(rec);
  save(r);
  log(id, `registered (${harness}${rec.model ? ` · ${rec.model}` : ''})`);
  console.log(`registered ${id} on ${harness}`);
}

function claim(o) {
  const r = load();
  const id = o._[0] || (console.error('claim <id>'), process.exit(1));
  const t = find(r, id);
  if (t.owner && t.owner !== o.agent) (console.error(`${id} already owned by ${t.owner}`), process.exit(1));
  if (!o.agent) (console.error('claim <id> --agent <name>'), process.exit(1));
  t.owner = o.agent;
  t.status = 'doing';
  t.updatedAt = now();
  save(r);
  log(o.agent, `claimed ${id} — ${t.title}`);
  console.log(`claimed ${id}`);
}

function update(o) {
  const r = load();
  const id = o._[0] || (console.error('update <id> [-m msg] [--status s]'), process.exit(1));
  const t = find(r, id);
  if (o.status) {
    if (!STATUS.includes(o.status)) (console.error(`status must be one of ${STATUS.join(', ')}`), process.exit(1));
    t.status = o.status;
  }
  t.updatedAt = now();
  save(r);
  log(o.agent || t.owner, `updated ${id}${o.status ? ` -> ${o.status}` : ''}${o.m ? `: ${o.m}` : ''}`);
  console.log(`updated ${id}${o.status ? ` -> ${o.status}` : ''}`);
}

function done(o) {
  const r = load();
  const id = o._[0] || (console.error('done <id>'), process.exit(1));
  const t = find(r, id);
  t.status = 'done';
  t.updatedAt = now();
  save(r);
  log(o.agent || t.owner, `done ${id}${o.m ? `: ${o.m}` : ''}`);
  console.log(`done ${id}`);
}

function add(o) {
  const r = load();
  const title = o._.join(' ') || o.title;
  if (!title) (console.error('add "title" [--module m] [--accept "..."]'), process.exit(1));
  const n = r.tasks.reduce((m, t) => Math.max(m, parseInt(t.id.slice(2), 10) || 0), 0) + 1;
  const id = `T-${String(n).padStart(3, '0')}`;
  r.tasks.push({ id, title, status: 'todo', module: o.module || null, owner: null, deps: [], acceptance: o.accept || null, updatedAt: now(), links: [] });
  save(r);
  render(load());
  console.log(`added ${id}: ${title}`);
}

const cell = (t) => `\`${t.id}\` ${t.title}${t.owner ? ` _(${t.owner})_` : ''}`;

function render(r) {
  const sorted = [...r.tasks].sort((a, b) => (ORDER[a.status] - ORDER[b.status]) || a.id.localeCompare(b.id));

  const todo = [`# TODO`, ``, `_Generated by \`node tasks/bin/tasks.mjs board\`. Do not edit._`, ``, `| # | Task | Module | Status | Owner | Acceptance |`, `|---|---|---|---|---|---|`];
  for (const t of sorted) todo.push(`| ${t.id} | ${t.title} | ${t.module || '—'} | ${t.status} | ${t.owner || '—'} | ${t.acceptance || '—'} |`);
  writeFileSync(join(TASKS, 'TODO.md'), todo.join('\n') + '\n');

  const cols = [`# BOARD`, ``, `_Generated by \`node tasks/bin/tasks.mjs board\`. Do not edit._`, ``];
  for (const s of ['doing', 'review', 'todo', 'blocked', 'done']) {
    const items = sorted.filter((t) => t.status === s);
    cols.push(`## ${s} (${items.length})`, ``);
    cols.push(items.length ? items.map((t) => `- ${cell(t)}`).join('\n') : '_none_', ``);
  }
  writeFileSync(join(TASKS, 'BOARD.md'), cols.join('\n'));
}

function status(r) {
  const by = (s) => r.tasks.filter((t) => t.status === s).length;
  console.log(`Cinemacore board — ${r.tasks.length} tasks`);
  console.log(`  doing ${by('doing')} · review ${by('review')} · todo ${by('todo')} · blocked ${by('blocked')} · done ${by('done')}`);
  console.log(`  agents: ${r.agents.length ? r.agents.map((a) => `${a.id}(${a.harness})`).join(', ') : 'none registered'}`);
  const active = r.tasks.filter((t) => t.status === 'doing' || t.status === 'review');
  if (active.length) console.log(`  active: ${active.map((t) => t.id).join(', ')}`);
}

const HELP = `Cinemacore task CLI

  register --agent <name> --harness <harness>
  claim    <id> --agent <name>
  update   <id> [-m msg] [--status todo|doing|review|blocked|done] [--agent name]
  done     <id> [-m msg] [--agent name]
  add      "title" [--module m] [--accept "criteria"]
  status
  board`;

const cmd = process.argv[2];
const o = parse(process.argv.slice(3));
switch (cmd) {
  case 'register': register(o); break;
  case 'claim': claim(o); break;
  case 'update': update(o); break;
  case 'done': done(o); break;
  case 'add': add(o); break;
  case 'board': render(load()); console.log('regenerated TODO.md and BOARD.md'); break;
  case 'status': status(load()); break;
  default: console.log(HELP); process.exit(cmd ? 1 : 0);
}
